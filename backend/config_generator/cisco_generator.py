# ============================================================
# GENERATE ALL CONFIGURATIONS
# ============================================================

def generate_all_configurations(
    plan: Dict[str, Any]
) -> Dict[str, str]:
    """
    Generate configurations for all devices
    in the NetworkPlan.
    """

    configurations = {}

    devices = plan.get(
        "devices",
        []
    )

    # --------------------------------------------------------
    # CORE
    # --------------------------------------------------------

    core_exists = any(
        "Core Switch" in device.get(
            "device_type",
            ""
        )
        for device in devices
    )

    if core_exists:
        configurations["Core Switch"] = (
            generate_core_switch_config(plan)
        )

    # --------------------------------------------------------
    # DISTRIBUTION
    # --------------------------------------------------------

    distribution_count = 0

    for device in devices:

        device_type = device.get(
            "device_type",
            ""
        )

        if "Distribution Switch" in device_type:

            distribution_count = device.get(
                "quantity",
                1
            )

            break

    for i in range(
        1,
        distribution_count + 1
    ):

        configurations[
            f"Distribution Switch {i}"
        ] = generate_distribution_switch_config(
            plan,
            i
        )

    # --------------------------------------------------------
    # ACCESS
    # --------------------------------------------------------

    access_count = 0

    for device in devices:

        device_type = device.get(
            "device_type",
            ""
        )

        if "Access Switch" in device_type:

            access_count = device.get(
                "quantity",
                1
            )

            break

    for i in range(
        1,
        access_count + 1
    ):

        configurations[
            f"Access Switch {i}"
        ] = generate_access_switch_config(
            plan,
            i
        )

    # --------------------------------------------------------
    # ROUTER
    # --------------------------------------------------------

    router_exists = any(
        (
            "Router" in device.get(
                "device_type",
                ""
            )
            or
            "Internet Router" in device.get(
                "device_type",
                ""
            )
        )
        for device in devices
    )

    if router_exists:

        configurations[
            "Internet Router"
        ] = generate_router_config(plan)

    # --------------------------------------------------------
    # FIREWALL
    # --------------------------------------------------------

    firewall_exists = any(
        "Firewall" in device.get(
            "device_type",
            ""
        )
        for device in devices
    )

    if firewall_exists:

        configurations[
            "Firewall"
        ] = generate_firewall_config(plan)

    return configurations